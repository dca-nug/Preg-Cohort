"""
=============================================================================
 STEP 10 -- FOREST PLOTS
=============================================================================

Draws the four forest plots reported in the manuscript:

    1_baseline.png              baseline characteristics across the three levels
    2_early_pregnancy.png       abortive outcome and early-pregnancy conditions
    3_later_complications.png   later pregnancy complications
    4_delivery_outcomes.png     delivery outcomes

WHY THIS READS A CSV RATHER THAN THE WORKBOOK
---------------------------------------------
The previous version parsed the formatted 'OR (95% CI)' string out of Excel
cells with a regular expression. Those cells carry rich text when the sparse
marker is applied, and a rich-text cell does not return a plain string, so the
regular expression can fail on exactly the rows that most need attention.
This version reads `or_long.csv` from step 8, which holds the estimate, both
confidence limits, and the estimability status as separate numeric fields.

MATCHING BY CODE, NOT BY LABEL
------------------------------
The previous version selected conditions by their display label, using an exact
dictionary lookup. Display labels are not stable across scripts: the odds-ratio
script labels `abortive` as 'Abortive pregnancy' while the supplementary tables
call it 'Abortive outcome'. An exact lookup on a label that has drifted returns
nothing and the point is silently omitted, which is how the primary outcome row
came to be blank rather than obviously wrong.

Groups are therefore defined by condition CODE (`abortive`, `preecl`, ...),
which is generated by the pipeline and cannot drift. Display labels are taken
from a single mapping so that renaming a row changes one line.

VISIT- AND INDIVIDUAL-LEVEL SERIES
----------------------------------
Those two series come from a separate analysis that operates on the visit-level
and individual-level datasets. If its output is not present, the corresponding
series are omitted and the figures are drawn from the pregnancy-level phases
alone. The script states clearly which series were drawn, so a missing series
cannot be mistaken for an absent association.

Two input formats are accepted, in this order of preference:

    or_long_visit_individual.csv   long format with columns level, code, odds_ratio,
                                   ci_lower, ci_upper
    or_visit_individual.xlsx       the earlier workbook, parsed for compatibility

NOT ESTIMABLE
-------------
Associations flagged as not estimable in step 8 are not plotted. Where a row has
no plottable estimate in any series it is annotated on the axis rather than left
looking like a null result.

INPUT
-----
    or_long.csv                          from step 8
    or_long_visit_individual.csv         optional
    or_visit_individual.xlsx             optional, legacy

OUTPUT
------
    1_baseline.png, 2_early_pregnancy.png,
    3_later_complications.png, 4_delivery_outcomes.png
    Figure_or_by_level.png               main-text figure: panels (a)-(c) in one
                                         file, log scale, estimable only
    forest_series_report.csv             which series were available per row
    benchmark_step10.csv                  per-stage timing and memory
    environment_step10.txt                library versions and machine specification

USAGE
-----
    python 10_forest_plots.py
    python 10_forest_plots.py --figure-only   rebuild only Figure_or_by_level.png
=============================================================================
"""

