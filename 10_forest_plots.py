def load_pregnancy_level(path: Path) -> tuple[dict, dict]:
    """Return {phase: {code: (or, lo, hi)}} and {code: label}."""
    if not path.exists():
        sys.exit(f"[FATAL] {path} not found. Run step 8 first.")
    df = pd.read_csv(path)
    need = {"code", "phase", "odds_ratio", "ci_lower", "ci_upper", "estimability"}
    missing = need - set(df.columns)
    if missing:
        sys.exit(f"[FATAL] {path} is missing columns: {sorted(missing)}")

    plottable = df[~df["estimability"].astype(str).str.startswith("not estimable")]
    n_drop = len(df) - len(plottable)
    print(f"    {len(df):,} associations, {n_drop:,} not estimable and not plotted")

    phases: dict[str, dict] = {"b": {}, "c": {}, "a": {}, "none": {}}
    for _, r in plottable.iterrows():
        ph = str(r["phase"])
        if ph not in phases:
            continue
        phases[ph][str(r["code"])] = (float(r["odds_ratio"]),
                                      float(r["ci_lower"]),
                                      float(r["ci_upper"]))
    labels = dict(zip(df["code"].astype(str), df["condition"].astype(str)))
    for k, v in DISPLAY.items():
        labels[k] = v
    for ph in ("b", "c", "a", "none"):
        print(f"      phase {ph:<5}: {len(phases[ph]):>4} plottable estimates")
    return phases, labels


def parse_or_string(s) -> tuple | None:
    if s is None:
        return None
    m = re.search(r"([\d.]+)\s*\(\s*([\d.]+)\s*[-\u2013]\s*([\d.]+)\)", str(s))
    return (float(m.group(1)), float(m.group(2)), float(m.group(3))) if m else None


def load_visit_individual() -> tuple[dict, dict, str]:
    """Visit- and individual-level estimates keyed by code, if available."""
    if VI_LONG.exists():
        df = pd.read_csv(VI_LONG)
        need = {"level", "code", "odds_ratio", "ci_lower", "ci_upper"}
        if not need <= set(df.columns):
            print(f"    [WARNING] {VI_LONG.name} lacks {sorted(need - set(df.columns))};"
                  " series omitted")
            return {}, {}, "none"
        vis, ind = {}, {}
        for _, r in df.iterrows():
            tgt = vis if str(r["level"]).lower().startswith("visit") else ind
            tgt[str(r["code"])] = (float(r["odds_ratio"]), float(r["ci_lower"]),
                                   float(r["ci_upper"]))
        print(f"    visit {len(vis)}, individual {len(ind)} estimates "
              f"<- {VI_LONG.name}")
        return vis, ind, "long csv"

    if VI_EXCEL.exists():
        try:
            df = pd.read_excel(VI_EXCEL, sheet_name=VI_SHEET)
        except Exception as exc:
            print(f"    [WARNING] could not read {VI_EXCEL.name}: {exc}")
            return {}, {}, "none"
        if "code" not in df.columns:
            print(f"    [WARNING] {VI_EXCEL.name} has no 'code' column; matching "
                  "by label is unreliable, so the series are omitted. Re-export "
                  "with a code column or supply or_long_visit_individual.csv.")
            return {}, {}, "none"
        vis, ind = {}, {}
        for _, r in df.iterrows():
            code = str(r["code"])
            v = parse_or_string(r.get("Visit OR (95% CI)"))
            i = parse_or_string(r.get("Individual OR (95% CI)"))
            if v:
                vis[code] = v
            if i:
                ind[code] = i
        print(f"    visit {len(vis)}, individual {len(ind)} estimates "
              f"<- {VI_EXCEL.name}")
        return vis, ind, "legacy workbook"

    print("    visit- and individual-level output not found; those two series "
          "will be omitted")
    return {}, {}, "none"


def draw_point(ax, y, est, style, xpad, annotate=True) -> bool:
    if est is None:
        return False
    orr, lo, hi = est
    ax.plot(orr, y, linestyle="none", markersize=6, markeredgecolor="black",
            markeredgewidth=0.4, zorder=3, **style)
    ax.plot([lo, hi], [y, y], color=style["color"], lw=1.3, zorder=2)
    ax.plot([lo, lo], [y - 0.05, y + 0.05], color=style["color"], lw=1.1)
    ax.plot([hi, hi], [y - 0.05, y + 0.05], color=style["color"], lw=1.1)
    if annotate:
        ax.text(hi + xpad, y, f"{orr:.3f} ({lo:.3f}\u2013{hi:.3f})",
                va="center", ha="left", fontsize=6)
    return True


def despine(ax) -> None:
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)


def baseline_plot(vis, ind, phases, labels, report) -> None:
    fig, ax = plt.subplots(figsize=(9, 4.2))
    yt, yl = [], []
    for i, code in enumerate(BASELINE_CODES):
        y = len(BASELINE_CODES) - 1 - i
        yt.append(y)
        yl.append(labels.get(code, code))
        drawn = []
        if draw_point(ax, y + 0.22, vis.get(code), STYLE["visit_b"], 0.004):
            drawn.append("visit")
        if draw_point(ax, y + 0.00, ind.get(code), STYLE["individual_b"], 0.004):
            drawn.append("individual")
        if draw_point(ax, y - 0.22, phases["none"].get(code),
                      STYLE["pregnancy_b"], 0.004):
            drawn.append("pregnancy")
        report.append({"figure": "1_baseline", "code": code,
                       "label": labels.get(code, code),
                       "series_drawn": ",".join(drawn) or "none"})
        if not drawn:
            ax.text(1.0, y, "  no estimate available", va="center",
                    ha="left", fontsize=7, color="#B00020")

    ax.axvline(1.0, color="gray", ls="--", lw=1)
    ax.set_yticks(yt)
    ax.set_yticklabels(yl)
    ax.set_ylim(-0.6, len(BASELINE_CODES) - 0.4)
    ax.set_xlabel("Odds ratio (95% CI)")
    ax.set_title("Baseline characteristics across the three analytic levels")
    ax.grid(axis="x", ls=":", alpha=0.4)
    despine(ax)
    handles = [Line2D([0], [0], **STYLE["visit_b"], ls="none", label="Visit level"),
               Line2D([0], [0], **STYLE["individual_b"], ls="none",
                      label="Individual level"),
               Line2D([0], [0], **STYLE["pregnancy_b"], ls="none",
                      label="Pregnancy level")]
    ax.legend(handles=handles, loc="center left", bbox_to_anchor=(1.01, 0.5),
              frameon=False)
    fig.tight_layout()
    fig.savefig(OUT_DIR / "1_baseline.png", dpi=DPI, bbox_inches="tight")
    plt.close(fig)
    print("    saved 1_baseline.png")


def condition_plot(codes, title, fname, vis, ind, phases, labels, report) -> None:
    series = [("visit", vis), ("individual", ind), ("before", phases["b"]),
              ("current", phases["c"]), ("after", phases["a"])]
    offs = [0.30, 0.15, 0.0, -0.15, -0.30]

    fig_h = max(4.0, 0.95 * len(codes))
    fig, ax = plt.subplots(figsize=(11, fig_h))
    yt, yl = [], []
    for i, code in enumerate(codes):
        y = len(codes) - 1 - i
        yt.append(y)
        yl.append(labels.get(code, code))
        drawn = []
        for (key, dct), off in zip(series, offs):
            if draw_point(ax, y + off, dct.get(code), STYLE[key], 0.05):
                drawn.append(key)
        report.append({"figure": fname, "code": code,
                       "label": labels.get(code, code),
                       "series_drawn": ",".join(drawn) or "none"})
        if not drawn:
            ax.text(1.0, y, "  no estimable association", va="center",
                    ha="left", fontsize=7, color="#B00020")

    ax.axvline(1.0, color="red", ls="--", lw=1.2)
    ax.set_yticks(yt)
    ax.set_yticklabels(yl, fontsize=8)
    ax.set_ylim(-0.6, len(codes) - 0.4)
    ax.set_xlabel("Odds ratio (95% CI)")
    ax.set_title(title)
    ax.grid(axis="x", ls=":", alpha=0.4)
    despine(ax)
    handles = [Line2D([0], [0], **STYLE[k], ls="none", label=lab)
               for k, lab in [("visit", "Visit level"),
                              ("individual", "Individual level"),
                              ("before", "Before pregnancy"),
                              ("current", "Current pregnancy"),
                              ("after", "After pregnancy")]]
    ax.legend(handles=handles, loc="upper left", bbox_to_anchor=(1.005, 1.0),
              frameon=True)
    fig.tight_layout()
    fig.savefig(OUT_DIR / fname, dpi=DPI, bbox_inches="tight")
    plt.close(fig)
    print(f"    saved {fname}")


# =============================================================================
# MAIN-TEXT FIGURE: PREGNANCY-RELATED CONDITIONS ACROSS LEVELS, ONE FILE
# =============================================================================
# The three condition plots above are kept for checking. This builds the
# journal version as a single file: panels (a)-(c) stacked, log odds-ratio
# axis, no value labels (the values are in the supplementary table), the
# colours of the before/after-QC scatter in step 14, and only estimable
# associations (flagged ones, any cell below five, are left out as stated in
# the Methods). IJE requires at least 3600 px width.
#   python 10_forest_plots.py --figure-only   rebuilds just this file

FIG_MAIN     = "Figure_or_by_level.png"
FIG_MAIN_DPI = 600                     # 7.5 in x 600 dpi = 4500 px wide
# Panel letters are printed below each panel; the panel descriptions belong in
# the figure caption, not in the image.
FIG_PANELS = [("a", "Abortive outcome and early-pregnancy conditions", EARLY_CODES),
              ("b", "Later pregnancy complications", LATER_CODES),
              ("c", "Delivery outcomes", DELIVERY_CODES)]
FIG_SERIES = [  # key, legend label, colour, marker  (matches step 14 scatter)
    ("visit", "Visit level", "#000000", "D"),
    ("individual", "Individual level", "#777777", "s"),
    ("b", "Pregnancy level, before pregnancy", "#0072B2", "o"),
    ("c", "Pregnancy level, during pregnancy", "#D55E00", "o"),
    ("a", "Pregnancy level, after pregnancy", "#009E73", "o"),
]
UK_SPELLING = {"Hemorrhage": "Haemorrhage", "hemorrhage": "haemorrhage",
               "Edema": "Oedema", "edema": "oedema", "Anemia": "Anaemia",
               "anemia": "anaemia", "Hematolog": "Haematolog",
               "hematolog": "haematolog", "Diarrhea": "Diarrhoea",
               "diarrhea": "diarrhoea", "Tumor": "Tumour", "tumor": "tumour"}


def _uk(text: str) -> str:
    for us, gb in UK_SPELLING.items():
        text = text.replace(us, gb)
    return text


def _estimable(df: pd.DataFrame) -> pd.DataFrame:
    return df[(df["estimability"] == "estimable") & df["odds_ratio"].notna()]


def main_text_figure() -> None:
    import numpy as np
    preg = pd.read_csv(OR_LONG)
    if not VI_LONG.exists():
        print(f"    [skip] {VI_LONG.name} not found; run step 9 first")
        return
    vi = pd.read_csv(VI_LONG)
    est = {}
    for _, r in _estimable(vi).iterrows():
        est[(str(r["level"]).lower(), str(r["code"]))] = (r["odds_ratio"], r["ci_lower"], r["ci_upper"])
    for _, r in _estimable(preg).iterrows():
        est[(str(r["phase"]), str(r["code"]))] = (r["odds_ratio"], r["ci_lower"], r["ci_upper"])
    labels = {str(c): _uk(str(l)) for c, l in zip(preg["code"], preg["condition"])}
    labels.update({k: v for k, v in DISPLAY.items()})

    codes_all = [c for _, _, cs in FIG_PANELS for c in cs]
    vals = [v for (k, c), v in est.items() if c in codes_all]
    nice = [0.01, 0.02, 0.05, 0.1, 0.2, 0.5, 1, 2, 5, 10, 20, 50, 100, 200]
    lo = max(t for t in nice if t <= min(v[1] for v in vals))
    hi = min(t for t in nice if t >= max(v[2] for v in vals))

    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 8})
    heights = [len(cs) + 1.2 for _, _, cs in FIG_PANELS]
    fig, axes = plt.subplots(len(FIG_PANELS), 1, figsize=(7.5, 0.28 * sum(heights) + 0.9),
                             gridspec_kw={"height_ratios": heights}, sharex=True)
    offs = np.linspace(0.32, -0.32, len(FIG_SERIES))
    n_drawn = 0
    for ax, (tag, title, codes) in zip(axes, FIG_PANELS):
        for i, code in enumerate(codes):
            y = len(codes) - 1 - i
            if i % 2 == 0:
                ax.axhspan(y - 0.5, y + 0.5, color="#f4f4f4", zorder=0, lw=0)
            for (key, _, colr, mk), off in zip(FIG_SERIES, offs):
                e = est.get((key, code))
                if e is None:
                    continue
                o, l, h = e
                ax.plot([l, h], [y + off] * 2, color=colr, lw=0.9, zorder=2)
                ax.plot(o, y + off, marker=mk, color=colr, ms=3.6, ls="none",
                        markeredgecolor="white", markeredgewidth=0.3, zorder=3)
                n_drawn += 1
        ax.axvline(1, color="black", lw=0.7, zorder=1)
        ax.set_yticks(range(len(codes)))
        ax.set_yticklabels([labels.get(c, c) for c in reversed(codes)])
        ax.set_ylim(-0.6, len(codes) - 0.4)
        ax.tick_params(axis="y", length=0)
        last = ax is axes[-1]
        ax.annotate(f"({tag})", xy=(0.5, 0), xycoords="axes fraction",
                    xytext=(0, -34 if last else -6), textcoords="offset points",
                    ha="center", va="top", fontsize=9)
        for sp in ("top", "right", "left"):
            ax.spines[sp].set_visible(False)
    ax = axes[-1]
    ax.set_xscale("log"); ax.set_xlim(lo, hi)
    ticks = [t for t in nice if lo <= t <= hi]
    ax.set_xticks(ticks); ax.set_xticklabels([f"{t:g}" for t in ticks])
    ax.minorticks_off()
    ax.set_xlabel("Odds ratio for abortive outcome (95% CI, log scale)")
    handles = [Line2D([], [], color=c, marker=m, ls="-", lw=0.9, ms=4, label=lab)
               for _, lab, c, m in FIG_SERIES]
    fig.legend(handles=handles, loc="lower center", ncol=2, frameon=False,
               bbox_to_anchor=(0.5, 0.0), fontsize=7.5, columnspacing=1.5)
    fig.tight_layout(rect=(0, 0.055, 1, 1), h_pad=2.2)
    fig.savefig(OUT_DIR / FIG_MAIN, dpi=FIG_MAIN_DPI)
    plt.close(fig)
    print(f"    saved {FIG_MAIN}: {len(codes_all)} conditions, {n_drawn} estimates "
          f"(estimable only)")


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    print("=" * 74)
    print(" STEP 10 -- FOREST PLOTS")
    print("=" * 74)
    print(environment_report(str(OUT_DIR / "environment_step10.txt")))
    warn_if_no_psutil()

    bench = Bench("step 10, forest plots")

    with bench.stage("Load pregnancy-level estimates", "pandas") as b:
        phases, labels = load_pregnancy_level(OR_LONG)
        b["rows_out"] = sum(len(v) for v in phases.values())

    with bench.stage("Load visit- and individual-level estimates", "pandas") as b:
        vis, ind, source = load_visit_individual()
        b["rows_out"] = len(vis) + len(ind)

    report: list[dict] = []
    with bench.stage("Draw figures", "matplotlib") as b:
        baseline_plot(vis, ind, phases, labels, report)
        condition_plot(EARLY_CODES,
                       "Abortive outcome and early-pregnancy conditions",
                       "2_early_pregnancy.png", vis, ind, phases, labels, report)
        condition_plot(LATER_CODES, "Later pregnancy complications",
                       "3_later_complications.png", vis, ind, phases, labels,
                       report)
        condition_plot(DELIVERY_CODES, "Delivery outcomes",
                       "4_delivery_outcomes.png", vis, ind, phases, labels,
                       report)
        main_text_figure()
        b["rows_out"] = len(report)

    rep = pd.DataFrame(report)
    rep.to_csv(OUT_DIR / "forest_series_report.csv", index=False)

    print(f"\n    visit / individual series source : {source}")
    blank = rep[rep["series_drawn"] == "none"]
    if len(blank):
        print(f"    rows with no plottable estimate  : {len(blank)}")
        for _, r in blank.iterrows():
            print(f"      {r['figure']:<26} {r['label'][:44]}")
    else:
        print("    every row has at least one plottable estimate")

    bench.finalise(str(OUT_DIR / "benchmark_step10.csv"), rows_out=len(rep))
    print(f"\nOutput written to {OUT_DIR.resolve()}")


if __name__ == "__main__":
    if "--figure-only" in sys.argv:
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        main_text_figure()
    else:
        main()